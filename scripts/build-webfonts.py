"""Build the checked-in website font subsets from their original font files."""

import argparse
import hashlib
import json
from dataclasses import dataclass
from itertools import chain, groupby
from pathlib import Path
from shutil import copyfile
from tempfile import TemporaryDirectory

from fontTools import subset
from fontTools.ttLib import TTFont


ROOT = Path(__file__).resolve().parents[1]
FRONTEND = ROOT / 'apps/frontend/app'
SAKURA = FRONTEND / 'themes/sakura'


@dataclass(frozen=True)
class Webfont:
    family: str
    prefix: str
    source_label: str
    sha256: str
    source: Path | None = None


FONTS = {
    'wenkai': Webfont(
        family='Sakura LXGW WenKai Mono',
        prefix='lxgw-wenkai-mono-',
        source_label='LXGW WenKai v1.530',
        sha256='895ce1d2fa00d5ca3bec0329d38e3190454f4b5fa7b4733f491c419faf9753a1',
    ),
    'bubble-candy': Webfont(
        family='Bubble Candy',
        prefix='bubble-candy-',
        source_label='the original Bubble Candy WOFF2',
        sha256='fb93a7d9a23ee1edb9065d45b58cab02a8d4254bd44107ff54fa7757dfa1009a',
        source=ROOT / 'scripts/fonts/bubble-candy.woff2',
    ),
}


def parse_ranges(value):
    points = set()
    for extent in value.split(','):
        first, _, last = extent.strip().upper().removeprefix('U+').partition('-')
        points.update(range(int(first, 16), int(last or first, 16) + 1))
    return points


def css_ranges(points):
    ranges = []
    for _, group in groupby(enumerate(sorted(points)), lambda entry: entry[1] - entry[0]):
        run = [point for _, point in group]
        first, last = run[0], run[-1]
        ranges.append(f'U+{first:X}' if first == last else f'U+{first:X}-{last:X}')
    return ', '.join(ranges)


def variation_mappings(font):
    return {
        (base, selector): glyph
        for table in font['cmap'].tables if table.format == 14
        for selector, entries in table.uvsDict.items()
        for base, glyph in entries
    }


def partition(points, variation_bases):
    # Noto Sans SC's higher numbered slices group Chinese glyphs by web usage.
    # The already locked Fontsource dependency supplies these codepoint sets.
    ranges_file = ROOT / 'node_modules/@fontsource/noto-sans-sc/unicode.json'
    noto = json.loads(ranges_file.read_text(encoding='utf-8'))
    ranked = {rank: parse_ranges(noto[f'[{rank}]']) for rank in range(100, 120)}
    ui_files = chain(
        [FRONTEND / 'i18n/public.ts', ROOT / 'packages/content/src/types.ts'],
        sorted(SAKURA.rglob('*.vue')),
    )
    ui = {
        ord(character)
        for path in ui_files
        for character in path.read_text(encoding='utf-8')
    }
    basic = parse_ranges(
        '0-36F,1E00-1EFF,2000-209F,20A0-20CF,2190-21FF,3000-303F,FE00-FE6F,FF00-FF60,FFE0-FFEF'
    )
    kana = parse_ranges('3040-30FF,31F0-31FF,FF61-FF9F,1AFF0-1AFFF,1B000-1B16F')
    # Keep Latin and kana marks with their script, and variations with their base glyphs.
    groups = [
        ('basic', basic | variation_bases | {point for point in ui if point < 0x3000}),
        ('kana', kana),
        ('common', ui | set.union(*(ranked[rank] for rank in range(115, 120)))),
    ]
    groups.extend(
        (f'frequent-{start}', set.union(*(ranked[rank] for rank in range(start, start + 3))))
        for start in range(112, 99, -3)
    )
    remaining = set(points)
    for name, group in groups:
        selected = remaining.intersection(group)
        if selected:
            yield name, selected
            remaining.difference_update(selected)

    # Pack the long tail in codepoint order to keep CSS ranges compact.
    tail = sorted(remaining)
    for start in range(0, len(tail), 512):
        yield f'u{tail[start]:x}', set(tail[start:start + 512])


def build_subsets(webfont, source, output):
    with TTFont(source, lazy=True) as original:
        cmap = original.getBestCmap()
        variations = variation_mappings(original)

    options = subset.Options()
    options.flavor = 'woff2'
    options.layout_features = ['*']
    options.glyph_names = True
    options.name_IDs = ['*']
    options.passthrough_tables = True
    options.recalc_timestamp = False

    rules = [f'/* Generated by scripts/build-webfonts.py from {webfont.source_label}. */']
    covered = set()
    for name, points in partition(cmap, {base for base, _ in variations}):
        filename = f'{webfont.prefix}{name}.woff2'
        expected = {point: cmap[point] for point in points}
        expected_variations = {
            key: glyph for key, glyph in variations.items() if key[0] in points
        }
        selectors = {selector for _, selector in expected_variations}
        assert not covered.intersection(points)
        covered.update(points)

        with subset.load_font(source, options) as font:
            worker = subset.Subsetter(options=options)
            worker.populate(unicodes=points | selectors)
            worker.subset(font)
            subset.save_font(font, output / filename, options)

        with TTFont(output / filename, lazy=True) as font:
            assert font.getBestCmap() == expected, filename
            assert variation_mappings(font) == expected_variations, filename

        rules.append(f"""@font-face {{
  font-family: '{webfont.family}';
  font-style: normal;
  font-weight: 400;
  font-display: swap;
  src: url('./{filename}') format('woff2');
  unicode-range: {css_ranges(points | selectors)};
}}""")

    assert covered == cmap.keys()
    return '\n\n'.join(rules) + '\n'


def main():
    parser = argparse.ArgumentParser(description=__doc__)
    parser.add_argument('font', choices=FONTS)
    parser.add_argument('source', type=Path, nargs='?', help='path to the original font')
    args = parser.parse_args()
    webfont = FONTS[args.font]
    source = args.source or webfont.source
    if source is None:
        parser.error(f'A source font is required for {args.font}')
    with source.open('rb') as original:
        if hashlib.file_digest(original, 'sha256').hexdigest() != webfont.sha256:
            parser.error(f'The font must match {webfont.source_label}')

    assets = FRONTEND / 'assets/fonts' / args.font
    with TemporaryDirectory() as directory:
        output = Path(directory)
        css = build_subsets(webfont, source, output)
        assets.mkdir(parents=True, exist_ok=True)
        for font in output.glob('*.woff2'):
            copyfile(font, assets / font.name)
        for old_font in assets.glob(f'{webfont.prefix}*.woff2'):
            if not (output / old_font.name).exists():
                old_font.unlink()
        (assets / f'{args.font}.css').write_text(css, encoding='utf-8')


if __name__ == '__main__':
    main()
